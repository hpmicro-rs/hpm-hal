pub mod ring_buffer {
    #[derive(Debug, defmt::Format)]
    pub struct RingBuffer<T: Copy> {
        buf: [T; 128],
        cursor: usize,
        size: usize,
        cap: usize,
    }

    unsafe impl<T: Copy> Sync for RingBuffer<T> {}
    unsafe impl<T: Copy> Send for RingBuffer<T> {}

    impl<T: Copy> RingBuffer<T> {
        pub const fn new() -> Self {
            RingBuffer {
                buf: unsafe { core::mem::zeroed() },
                cursor: 0,
                cap: 128,
                size: 0,
            }
        }

        pub fn push(&mut self, v: T) {
            self.buf[self.cursor] = v;
            self.cursor += 1;
            if self.cursor == self.cap {
                self.cursor = 0;
            }
            if self.size < self.cap {
                self.size += 1;
            }
        }

        pub const fn len(&self) -> usize {
            self.size
        }

        pub fn get(&self, i: usize) -> Option<T> {
            if i < self.size {
                let mut idx = (self.cursor as isize) - ((self.size - i) as isize);
                if idx < 0 {
                    idx += self.size as isize;
                }
                Some(self.buf[idx as usize])
            } else {
                None
            }
        }

        pub fn iter<'a>(&'a self) -> RingBufferIter<'a, T> {
            RingBufferIter { rb: self, pos: 0 }
        }
    }

    pub struct RingBufferIter<'a, T: Copy> {
        rb: &'a RingBuffer<T>,
        pos: usize,
    }

    impl<'a, T: Copy> core::iter::Iterator for RingBufferIter<'a, T> {
        type Item = T;

        fn next(&mut self) -> Option<Self::Item> {
            let ret = self.rb.get(self.pos);
            self.pos += 1;
            ret
        }
    }
}

