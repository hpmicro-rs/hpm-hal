static mut BUF: [[u32; 4096]; 2] = [[0; 4096]; 2];
static ACTIVE_BUF_INDEX: AtomicUsize = AtomicUsize::new(0);

#[inline]
fn get_active_buf() -> &'static mut [u32; 4096] {
    unsafe { &mut BUF[ACTIVE_BUF_INDEX.load(core::sync::atomic::Ordering::Relaxed)] }
}

#[inline]
fn get_inactive_buf() -> &'static mut [u32; 4096] {
    unsafe { &mut BUF[1 - ACTIVE_BUF_INDEX.load(core::sync::atomic::Ordering::Relaxed)] }
}

#[inline]
fn switch_buf() {
    ACTIVE_BUF_INDEX.store(
        1 - ACTIVE_BUF_INDEX.load(core::sync::atomic::Ordering::Relaxed),
        core::sync::atomic::Ordering::Relaxed,
    );
}

