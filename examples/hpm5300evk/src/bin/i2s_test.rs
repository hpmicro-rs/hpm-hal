#[embassy_executor::task]
async fn audio_task2(r: I2SResources) {
    println!("audio task started");

    let mut cfg = hal::spi::Config::default();
    cfg.frequency = Hertz::hz(2_000_000);
    // mosi, miso
    let mut ws = Output::new(r.ws, Level::High, Default::default());

    let mut spi = hal::spi::Spi::new_rxonly(r.spi2, r.sclk, r.sd, r.dma_ch1, cfg);

    info!("SPI freq {}", spi.frequency().0);

    loop {
        let mut buf = [0u32; 1024];

        for i in 0..512 {
            ws.set_low();
            spi.read(&mut buf[i..i + 1]).await;
            ws.set_high();
            spi.read(&mut buf[i + 1..i + 2]).await;
        }

        println!(" => {:08x?}", buf);

        Timer::after_millis(1000).await;
    }
}

